import assert from 'node:assert/strict';
import worker,{ThrowRelay} from '../cloud/worker.mjs';
const memory=new Map();
const storage={get:async k=>memory.get(k),put:async(k,v)=>memory.set(k,v),transaction:async fn=>fn(storage)};
let relay=new ThrowRelay({storage});
const token='a'.repeat(64);
const env={RELAY_TOKEN:token,ASSETS:{fetch:async()=>new Response('PAGE')},THROWS:{idFromName:x=>x,get:()=>({fetch:r=>relay.fetch(r)})}};
const req=(path,body,secret=token)=>new Request('https://pace.test'+path,{method:body===undefined?'GET':'POST',headers:{Authorization:'Bearer '+secret},...(body===undefined?{}:{body:JSON.stringify(body)})});
assert.equal((await worker.fetch(req('/'),env)).status,200);
assert.equal((await worker.fetch(req('/api/config'),env)).status,200);
assert.equal((await worker.fetch(req('/api/last',undefined,'wrong'),env)).status,401);
assert.equal((await worker.fetch(req('/api/last'),{...env,RELAY_TOKEN:null})).status,503);
assert.equal((await worker.fetch(req('/api/throw',{event:'throw',peak_g:true}),env)).status,400);
assert.equal((await worker.fetch(req('/api/throw',{event:'throw',peak_g:-1}),env)).status,400);
assert.equal((await worker.fetch(req('/api/throw',{event:'throw'}),env)).status,400);
assert.equal((await worker.fetch(req('/api/throw',{event:'throw',peak_g:2,motion_score:.3}),env)).status,200);
assert.equal((await worker.fetch(req('/api/throw',{event:'throw',peak_g:2}),env)).status,429);
relay=new ThrowRelay({storage}); // object instance recreation retains saved sequence and event
const last=await (await worker.fetch(req('/api/last'),env)).json();
assert.equal(last.sequence,1);assert.equal(last.event.peak_g,2);assert.ok(last.now>=last.event.at);
assert.equal(await (await worker.fetch(req('/api/result?sequence=1'),env)).text(),'pending');
assert.equal((await worker.fetch(req('/api/result',{sequence:1,success:'yes'}),env)).status,400);
assert.equal((await worker.fetch(req('/api/result',{sequence:2,success:true}),env)).status,409);
assert.equal((await worker.fetch(req('/api/result',{sequence:1,success:true},'wrong'),env)).status,401);
assert.equal((await worker.fetch(req('/api/result',{sequence:1,success:true}),env)).status,200);
assert.equal((await worker.fetch(req('/api/result',{sequence:1,success:true}),env)).status,200);
assert.equal((await worker.fetch(req('/api/result',{sequence:1,success:false}),env)).status,409);
assert.equal(await (await worker.fetch(req('/api/result?sequence=1'),env)).text(),'success');
memory.get('state').event.at-=1;
const next=await worker.fetch(req('/api/throw',{event:'throw',peak_g:3}),env);
assert.equal(next.headers.get('X-Throw-Sequence'),'2');
assert.equal(await (await worker.fetch(req('/api/result?sequence=1'),env)).text(),'stale');
assert.equal(await (await worker.fetch(req('/api/result?sequence=2'),env)).text(),'pending');
assert.equal((await worker.fetch(req('/api/result',{sequence:2,success:false}),env)).status,200);
assert.equal(await (await worker.fetch(req('/api/result?sequence=2'),env)).text(),'failure');
memory.get('state').event.at-=31;
assert.equal((await worker.fetch(req('/api/result',{sequence:2,success:false}),env)).status,410);
assert.equal((await worker.fetch(req('/api/throw',{event:'throw',padding:'x'.repeat(1100)}),env)).status,413);
assert.equal((await worker.fetch(req('/api/missing'),env)).status,404);
assert.equal((await worker.fetch(req('/api/last',{}),env)).status,405);
assert.equal(await (await worker.fetch(req('/api/encounter'),env)).text(),'none');
assert.equal((await worker.fetch(req('/api/encounter',{id:'test-1',active:true}),env)).status,200);
assert.equal(await (await worker.fetch(req('/api/encounter'),env)).text(),'present');
assert.equal((await worker.fetch(req('/api/encounter',{id:'test-1',active:false}),env)).status,200);
assert.equal(await (await worker.fetch(req('/api/encounter'),env)).text(),'none');
assert.equal((await worker.fetch(req('/api/encounter',{id:'test-1',active:true}),env)).status,409);
await worker.fetch(req('/api/encounter',{id:'test-2',active:true}),env);
await worker.fetch(req('/api/encounter',{id:'test-1',active:false}),env);
assert.equal(await (await worker.fetch(req('/api/encounter'),env)).text(),'present');
memory.get('encounter').updated-=46000;
assert.equal(await (await worker.fetch(req('/api/encounter'),env)).text(),'none');
assert.equal((await worker.fetch(req('/api/device',undefined,'wrong'),env)).status,401);
assert.equal((await worker.fetch(req('/api/device?sequence=-1'),env)).status,400);
let device=await worker.fetch(req('/api/device'),env);
assert.equal(device.headers.get('X-Device-Status'),'2');
assert.equal(device.headers.get('X-Encounter-State'),'none');
assert.equal(await device.text(),'idle');
await worker.fetch(req('/api/encounter',{id:'round-A',active:true}),env);
memory.get('state').event.at-=1;
let throwA=await worker.fetch(req('/api/throw',{event:'throw',peak_g:3,encounter_id:'round-A'}),env);
assert.equal(throwA.status,200);const seqA=(await throwA.json()).sequence;
await worker.fetch(req('/api/result',{sequence:seqA,success:true}),env);
await worker.fetch(req('/api/encounter',{id:'round-A',active:false}),env);
// The next buddy may appear between polls: identity still changes even with no observed "none".
await worker.fetch(req('/api/encounter',{id:'round-B',active:true}),env);
device=await worker.fetch(req('/api/device?sequence='+seqA),env);
assert.equal(device.headers.get('X-Encounter-Id'),'round-B');
assert.equal(device.headers.get('X-Encounter-State'),'present');
assert.equal(await device.text(),'success'); // old outcome accompanied by NEW identity; firmware resets first
memory.get('state').event.at-=1;
assert.equal((await worker.fetch(req('/api/throw',{event:'throw',peak_g:3,encounter_id:'round-A'}),env)).status,409);
const throwB=await worker.fetch(req('/api/throw',{event:'throw',peak_g:3,encounter_id:'round-B'}),env);
assert.equal(throwB.status,200);const seqB=(await throwB.json()).sequence;
assert.equal((await worker.fetch(req('/api/result',{sequence:seqA,success:true}),env)).status,409);
device=await worker.fetch(req('/api/device?sequence='+seqB),env);
assert.equal(device.headers.get('X-Encounter-Id'),'round-B');assert.equal(await device.text(),'pending');
// A late successful B result must not close the newer C encounter.
await worker.fetch(req('/api/encounter',{id:'round-C',active:true}),env);
assert.equal((await worker.fetch(req('/api/result',{sequence:seqB,success:true}),env)).status,200);
device=await worker.fetch(req('/api/device'),env);
assert.equal(device.headers.get('X-Encounter-Id'),'round-C');
memory.get('state').event.at-=1;
const throwC=await worker.fetch(req('/api/throw',{event:'throw',peak_g:3,encounter_id:'round-C'}),env);
const seqC=(await throwC.json()).sequence;
await worker.fetch(req('/api/result',{sequence:seqC,success:true}),env);
device=await worker.fetch(req('/api/device?sequence='+seqC),env);
assert.equal(device.headers.get('X-Encounter-State'),'none');assert.equal(await device.text(),'success');
console.log('Cloud auth, request limits, metrics, rate limit, persistent sequence and relay response passed.');
